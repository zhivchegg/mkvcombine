// Current language
let _lang = "en";

/**
 * Get translated string by key, with optional parameter substitution.
 * Usage: t("scan.found", { videos: 5, audio: 3, subs: 2 })
 */
function t(key, params) {
    let str = (TRANSLATIONS[_lang] && TRANSLATIONS[_lang][key])
        || (TRANSLATIONS["en"] && TRANSLATIONS["en"][key])
        || key;
    if (params) {
        for (const [k, v] of Object.entries(params)) {
            str = str.replace(new RegExp(`\\{${k}\\}`, "g"), v);
        }
    }
    return str;
}

/**
 * Switch language, save to localStorage, update all DOM elements.
 */
function setLang(code) {
    if (!TRANSLATIONS[code]) code = "en";
    _lang = code;
    localStorage.setItem("mkvcombine_lang", code);
    document.documentElement.lang = code;

    // Update language selector value
    const sel = document.getElementById("langSelect");
    if (sel) sel.value = code;

    // Static text elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
        el.textContent = t(el.dataset.i18n);
    });

    // Placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        el.placeholder = t(el.dataset.i18nPlaceholder);
    });

    // Aria labels
    document.querySelectorAll("[data-i18n-aria]").forEach(el => {
        el.setAttribute("aria-label", t(el.dataset.i18nAria));
    });
}

/**
 * Read saved language from localStorage, fallback to 'en', apply it.
 */
function initLang() {
    const saved = localStorage.getItem("mkvcombine_lang");
    const code = saved && TRANSLATIONS[saved] ? saved : "en";
    setLang(code);
}

